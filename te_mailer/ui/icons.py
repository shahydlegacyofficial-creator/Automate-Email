def svg_markup(name: str, color: str, stroke_width: float = 2.0) -> bytes:
    body = PATHS.get(name, PATHS["file"])
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="{stroke_width}" stroke-linecap="round" '
        f'stroke-linejoin="round">{body}</svg>'
    ).encode("utf-8")


class ThemedIconEngine(QIconEngine):
    """Paints an SVG icon using the active theme's colours at paint time."""

    def __init__(self, name: str, role: str = "text", checked_role: str | None = None):
        super().__init__()
        self.name = name
        self.role = role
        self.checked_role = checked_role

    def _color(self, mode, state) -> str:
        colors = theme.current()
        if mode == QIcon.Mode.Disabled:
            return colors["text_muted"]
        if state == QIcon.State.On and self.checked_role:
            return colors[self.checked_role]
        return colors.get(self.role, self.role)

    def paint(self, painter: QPainter, rect, mode, state):
        renderer = QSvgRenderer(QByteArray(svg_markup(self.name, self._color(mode, state))))
        renderer.render(painter, QRectF(rect))

    def pixmap(self, size: QSize, mode, state):
        ratio = 2.0
        pm = QPixmap(int(size.width() * ratio), int(size.height() * ratio))
        pm.fill(Qt.GlobalColor.transparent)
        painter = QPainter(pm)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        self.paint(painter, pm.rect(), mode, state)
        painter.end()
        pm.setDevicePixelRatio(ratio)
        return pm

    def clone(self):
        return ThemedIconEngine(self.name, self.role, self.checked_role)


def icon(name: str, role: str = "text", checked_role: str | None = None) -> QIcon:
    """``role`` is a theme colour key (text, text_muted, accent, on_accent, danger…)."""
    return QIcon(ThemedIconEngine(name, role, checked_role))


def render_png(name: str, color: str, size: int, path: str) -> None:
    pm = QPixmap(size, size)
    pm.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(QByteArray(svg_markup(name, color, 2.4))).render(painter, QRectF(0, 0, size, size))
    painter.end()
    pm.save(path, "PNG")
